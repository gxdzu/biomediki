function renderFaq(){
  const el = document.getElementById('faq-list');
  if(!el) return;
  el.innerHTML = FAQ_ITEMS.map((item, i) => `
    <div class="faq-item" onclick="toggleFaq(${i})">
      <div class="faq-q">
        <span>${esc(item.q)}</span>
        <svg class="faq-arrow" id="faq-arr-${i}" viewBox="0 0 16 16" width="14" height="14"><path d="M4 6l4 4 4-4" stroke="currentColor" stroke-width="1.3" fill="none" stroke-linecap="round" stroke-linejoin="round"/></svg>
      </div>
      <div class="faq-a hidden" id="faq-a-${i}">${esc(item.a)}</div>
    </div>
  `).join('');
}

function toggleFaq(i){
  const ans = document.getElementById(`faq-a-${i}`);
  const arr = document.getElementById(`faq-arr-${i}`);
  if(!ans) return;
  const open = !ans.classList.contains('hidden');
  ans.classList.toggle('hidden', open);
  if(arr) arr.style.transform = open ? '' : 'rotate(180deg)';
}
